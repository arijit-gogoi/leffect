-- Queue (specifications/37-queue.md §37): messages from producers to
-- consumers, each message to one consumer.

local leffect = require("leffect")
local Cause = leffect.Cause
local Effect = leffect.Effect
local Queue = leffect.Queue
local TestScheduler = require("leffect.scheduler.test")
local h = require("spec.helpers")

local run = Effect.runSync

local function list(...)
  return { n = select("#", ...), ... }
end

describe("Queue", function()
  local scheduler
  before_each(function()
    scheduler = TestScheduler.new()
  end)

  local function started(effect)
    return h.started(scheduler, effect)
  end

  it("offer then take keeps FIFO order", function()
    local q = run(Queue.unbounded())
    for i = 1, 3 do
      assert.is_true(run(q:offer(i)))
    end
    assert.are.same({ 1, 2, 3 }, { run(q:take()), run(q:take()), run(q:take()) })
  end)

  it("take on an empty queue waits for an offer", function()
    local q = run(Queue.unbounded())
    local taker = started(q:take())
    assert.is_nil(taker.exit)
    run(q:offer("x"))
    scheduler:flush()
    assert.are.equal("x", h.valueOf(taker.exit))
  end)

  it("serves takers in the order they started waiting", function()
    local q = run(Queue.unbounded())
    local a, b, c = started(q:take()), started(q:take()), started(q:take())
    run(q:offerAll(list(1, 2, 3)))
    scheduler:flush()
    assert.are.same({ 1, 2, 3 }, { h.valueOf(a.exit), h.valueOf(b.exit), h.valueOf(c.exit) })
  end)

  it("removes an interrupted taker; the next message goes to the next taker", function()
    local q = run(Queue.unbounded())
    local a, b = started(q:take()), started(q:take())
    a:interruptUnsafe()
    scheduler:flush()
    h.assertInterrupted(a.exit)
    run(q:offer("m"))
    scheduler:flush()
    assert.are.equal("m", h.valueOf(b.exit))
  end)

  it("passes the turn of a woken taker interrupted before it runs (invariant 24)", function()
    local q = run(Queue.unbounded())
    local a, b = started(q:take()), started(q:take())
    -- One step: the offer wakes a, then a is interrupted before it runs.
    assert.is_true(q:offerUnsafe("m"))
    a:interruptUnsafe()
    scheduler:flush()
    h.assertInterrupted(a.exit)
    assert.are.equal("m", h.valueOf(b.exit))
    assert.are.equal(0, q:sizeUnsafe())
  end)

  it("lets a woken taker that was overtaken wait again, in its place", function()
    local q = run(Queue.unbounded())
    local a = started(q:take())
    -- In one step, an offer wakes a, and a new take takes the message first.
    local barger = scheduler:fork(q:offer(1):flatMap(function()
      return q:take()
    end))
    scheduler:flush()
    assert.are.equal(1, h.valueOf(barger.exit))
    assert.is_nil(a.exit)
    run(q:offer(2))
    scheduler:flush()
    assert.are.equal(2, h.valueOf(a.exit))
  end)

  it("passes nil messages through, and takeAll's list has n", function()
    local q = run(Queue.unbounded())
    run(q:offer(nil))
    run(q:offer(2))
    run(q:offer(nil))
    assert.is_nil(run(q:take()))
    local all = run(q:takeAll())
    assert.are.equal(2, all.n)
    assert.are.equal(2, all[1])
    assert.is_nil(all[2])
  end)

  it("offerUnsafe never runs fiber code: the taker waits for the next flush", function()
    local q = run(Queue.unbounded())
    local log, record = h.recorder()
    started(q:take():flatMap(record))
    assert.is_true(q:offerUnsafe("m"))
    assert.are.same({}, log)
    scheduler:flush()
    assert.are.same({ "m" }, log)
  end)

  describe("bounded, suspending", function()
    it("an offer to a full queue waits, and a take lets the first waiting offer in", function()
      local q = run(Queue.bounded(1))
      run(q:offer(1))
      local offer = started(q:offer(2))
      assert.is_nil(offer.exit)
      assert.is_true(q:isFullUnsafe())
      assert.are.equal(1, run(q:take()))
      scheduler:flush()
      assert.is_true(h.valueOf(offer.exit))
      assert.are.equal(2, run(q:take()))
    end)

    it("waiting offers get in, in order", function()
      local q = run(Queue.bounded(1))
      run(q:offer(0))
      for i = 1, 3 do
        started(q:offer(i))
      end
      local got = {}
      for i = 1, 4 do
        got[i] = run(q:take())
      end
      assert.are.same({ 0, 1, 2, 3 }, got)
    end)

    it("offerAll adds what fits, waits for the rest, and succeeds with an empty list", function()
      local q = run(Queue.bounded(2))
      local offer = started(q:offerAll(list(1, 2, 3, 4)))
      assert.is_nil(offer.exit)
      assert.are.equal(2, q:sizeUnsafe())
      assert.are.same(list(1, 2), run(q:takeAll()))
      scheduler:flush()
      assert.are.same({ n = 0 }, h.valueOf(offer.exit))
      assert.are.same(list(3, 4), run(q:takeAll()))
    end)

    it("removes an interrupted waiting offer: its message never arrives", function()
      local q = run(Queue.bounded(1))
      run(q:offer(1))
      local offer = started(q:offer(2))
      offer:interruptUnsafe()
      scheduler:flush()
      h.assertInterrupted(offer.exit)
      assert.are.equal(1, run(q:take()))
      assert.is_nil(q:takeUnsafe())
    end)

    it("keeps an accepted offer accepted when its sender is interrupted (decision 54)", function()
      local q = run(Queue.bounded(1))
      run(q:offer(1))
      local offer = started(q:offer(2))
      -- One step: the take moves the waiting message in, then the offerer is
      -- interrupted before its wakeup runs.
      assert.are.equal(1, h.valueOf(q:takeUnsafe()))
      offer:interruptUnsafe()
      scheduler:flush()
      h.assertInterrupted(offer.exit)
      assert.are.equal(1, q:sizeUnsafe())
      assert.are.equal(2, h.valueOf(q:takeUnsafe()))
      assert.is_nil(q:takeUnsafe())
    end)
  end)

  describe("dropping", function()
    it("an offer to a full queue succeeds with false, and the queue keeps its messages", function()
      local q = run(Queue.dropping(2))
      assert.is_true(run(q:offer(1)))
      assert.is_true(run(q:offer(2)))
      assert.is_false(run(q:offer(3)))
      assert.are.same(list(1, 2), run(q:takeAll()))
    end)

    it("offerAll succeeds with the messages that didn't fit", function()
      local q = run(Queue.dropping(2))
      assert.are.same(list(3, 4), run(q:offerAll(list(1, 2, 3, 4))))
      assert.are.same(list(1, 2), run(q:takeAll()))
    end)
  end)

  describe("sliding", function()
    it("an offer to a full queue drops the oldest message, and succeeds with true", function()
      local q = run(Queue.sliding(2))
      run(q:offer(1))
      run(q:offer(2))
      assert.is_true(run(q:offer(3)))
      assert.are.same(list(2, 3), run(q:takeAll()))
    end)

    it("offerAll keeps the newest messages", function()
      local q = run(Queue.sliding(2))
      assert.are.same({ n = 0 }, run(q:offerAll(list(1, 2, 3, 4))))
      assert.are.same(list(3, 4), run(q:takeAll()))
    end)
  end)

  it("unbounded: an offer never waits", function()
    local q = run(Queue.unbounded())
    for i = 1, 1000 do
      assert.is_true(run(q:offer(i)))
    end
    assert.are.equal(1000, run(q:size()))
    assert.is_false(run(q:isFull()))
  end)

  it("takeAll takes every buffered message, waiting for one", function()
    local q = run(Queue.unbounded())
    local taker = started(q:takeAll())
    assert.is_nil(taker.exit)
    q:offerAllUnsafe(list(1, 2))
    scheduler:flush()
    assert.are.same(list(1, 2), h.valueOf(taker.exit))
  end)

  it("peek waits for a message, and doesn't remove it", function()
    local q = run(Queue.unbounded())
    local peeker = started(q:peek())
    local taker = started(q:take())
    assert.is_nil(peeker.exit)
    q:offerUnsafe("m")
    scheduler:flush()
    assert.are.equal("m", h.valueOf(peeker.exit))
    assert.are.equal("m", h.valueOf(taker.exit))
    q:offerUnsafe("n")
    assert.are.equal("n", run(q:peek()))
    assert.are.equal(1, q:sizeUnsafe())
  end)

  it("takeUnsafe returns a success, nil when empty, and the failure once Done", function()
    local q = run(Queue.unbounded())
    assert.is_nil(q:takeUnsafe())
    q:offerUnsafe(1)
    assert.are.equal(1, h.valueOf(q:takeUnsafe()))
    run(q:fail("e"))
    assert.are.same({ "e" }, Cause.failures(h.causeOf(q:takeUnsafe())))
  end)

  it("clear removes and returns the buffered messages, and lets waiting offers in", function()
    local q = run(Queue.bounded(2))
    run(q:offerAll(list(1, 2)))
    local offer = started(q:offer(3))
    assert.are.same(list(1, 2), run(q:clear()))
    scheduler:flush()
    assert.is_true(h.valueOf(offer.exit))
    assert.are.same(list(3), run(q:clear()))
    assert.are.same({ n = 0 }, run(q:clear()))
  end)

  it("size and isFull", function()
    local q = run(Queue.bounded(2))
    assert.are.equal(0, run(q:size()))
    run(q:offer(1))
    assert.is_false(run(q:isFull()))
    run(q:offer(2))
    assert.are.equal(2, run(q:size()))
    assert.is_true(run(q:isFull()))
    assert.is_true(q:isFullUnsafe())
  end)

  describe("finish", function()
    it("later offers succeed with false; takers drain, then fail with Done", function()
      local q = run(Queue.unbounded())
      run(q:offerAll(list(1, 2)))
      assert.is_true(run(q:finish()))
      assert.is_false(run(q:offer(3)))
      assert.are.equal(1, run(q:take()))
      assert.are.equal(2, run(q:take()))
      local cause = h.causeOf(Effect.runSyncExit(q:take()))
      assert.is_true(Cause.isDone(Cause.failures(cause)[1]))
      local caught = run(q:take():catchTag("Done", function(err)
        return Effect.succeed(err)
      end))
      assert.are.equal(Cause.Done(), caught)
    end)

    it("lets offers that were waiting in", function()
      local q = run(Queue.bounded(1))
      run(q:offer(1))
      local offer = started(q:offer(2))
      run(q:finish())
      assert.are.equal("Closing", q.state)
      assert.are.equal(1, run(q:take()))
      assert.are.equal(2, run(q:take()))
      assert.are.equal("Done", q.state)
      scheduler:flush()
      assert.is_true(h.valueOf(offer.exit))
    end)

    it("with nothing buffered, ends at once, and waiting takers fail with Done", function()
      local q = run(Queue.unbounded())
      local taker = started(q:take())
      run(q:finish())
      assert.are.equal("Done", q.state)
      scheduler:flush()
      assert.is_true(Cause.isDone(Cause.failures(h.causeOf(taker.exit))[1]))
    end)

    it("await succeeds once the queue is drained", function()
      local q = run(Queue.unbounded())
      q:offerUnsafe(1)
      local awaiter = started(q:await())
      q:finishUnsafe()
      scheduler:flush()
      assert.is_nil(awaiter.exit)
      run(q:take())
      scheduler:flush()
      h.valueOf(awaiter.exit)
    end)

    it("a second finish succeeds with false", function()
      local q = run(Queue.unbounded())
      assert.is_true(run(q:finish()))
      assert.is_false(run(q:finish()))
      assert.is_false(q:finishUnsafe())
    end)

    it("clear on a finished queue succeeds with an empty list", function()
      local q = run(Queue.unbounded())
      run(q:finish())
      assert.are.same({ n = 0 }, run(q:clear()))
    end)
  end)

  describe("fail", function()
    it("takers drain the queue, then fail with the error; await and clear fail too", function()
      local q = run(Queue.unbounded())
      local awaiter = started(q:await())
      q:offerUnsafe(1)
      run(q:fail("e"))
      assert.are.equal(1, run(q:take()))
      local cause = h.causeOf(Effect.runSyncExit(q:take()))
      assert.are.same({ "e" }, Cause.failures(cause))
      scheduler:flush()
      assert.are.same({ "e" }, Cause.failures(h.causeOf(awaiter.exit)))
      assert.are.same({ "e" }, Cause.failures(h.causeOf(Effect.runSyncExit(q:clear()))))
    end)

    it("failCause keeps its cause, and interrupt holds the fiber's id", function()
      local a, b = run(Queue.unbounded()), run(Queue.unbounded())
      run(a:failCause(Cause.die("d")))
      assert.are.same({ "d" }, Cause.defects(h.causeOf(a:takeUnsafe())))
      local fiber = scheduler:fork(b:interrupt())
      scheduler:flush()
      assert.are.same({ fiber.id }, Cause.interruptors(h.causeOf(b:takeUnsafe())))
    end)
  end)

  describe("shutdown", function()
    it("drops the buffer and interrupts waiting takers and awaiters", function()
      local q = run(Queue.unbounded())
      local taker = started(q:take())
      local awaiter = started(q:await())
      local other = run(Queue.unbounded())
      other:offerUnsafe(1)
      assert.is_true(run(q:shutdown()))
      assert.is_true(run(other:shutdown()))
      scheduler:flush()
      h.assertInterrupted(taker.exit)
      h.assertInterrupted(awaiter.exit)
      assert.are.equal(0, other:sizeUnsafe())
    end)

    it("resumes waiting offers with false, and a waiting offerAll with the rest", function()
      local q = run(Queue.bounded(1))
      q:offerUnsafe(0)
      local single = started(q:offer(1))
      local many = started(q:offerAll(list(2, 3)))
      assert.is_true(q:shutdownUnsafe())
      scheduler:flush()
      assert.is_false(h.valueOf(single.exit))
      assert.are.same(list(2, 3), h.valueOf(many.exit))
    end)

    it("later offers succeed with false, size is 0, and a second call gives false", function()
      local q = run(Queue.unbounded())
      q:offerUnsafe(1)
      run(q:shutdown())
      assert.is_false(run(q:offer(2)))
      assert.are.equal(0, run(q:size()))
      assert.is_false(run(q:shutdown()))
    end)

    it("on a Closing queue, waiting takers fail with the queue's error", function()
      local q = run(Queue.bounded(1))
      q:offerUnsafe(0)
      local offer = started(q:offer(1))
      run(q:fail("e"))
      run(q:shutdown())
      scheduler:flush()
      assert.is_false(h.valueOf(offer.exit))
      assert.are.same({ "e" }, Cause.failures(h.causeOf(Effect.runSyncExit(q:take()))))
    end)
  end)

  describe("takeN and takeBetween", function()
    it("wait for the minimum, and take at most the maximum", function()
      local q = run(Queue.unbounded())
      local taker = started(q:takeBetween(2, 3))
      q:offerUnsafe(1)
      scheduler:flush()
      assert.is_nil(taker.exit)
      q:offerAllUnsafe(list(2, 3, 4))
      scheduler:flush()
      assert.are.same(list(1, 2, 3), h.valueOf(taker.exit))
      assert.are.same(list(4), run(q:takeN(1)))
    end)

    it("on bounded(2), takeBetween(3, 5) takes 2", function()
      local q = run(Queue.bounded(2))
      local taker = started(q:takeBetween(3, 5))
      q:offerAllUnsafe(list(1, 2))
      scheduler:flush()
      assert.are.same(list(1, 2), h.valueOf(taker.exit))
    end)

    it("take fewer while the queue is Closing", function()
      local q = run(Queue.bounded(1))
      q:offerUnsafe(1)
      local offer = started(q:offer(2))
      run(q:finish())
      assert.are.same(list(1), run(q:takeN(3)))
      assert.are.same(list(2), run(q:takeN(3)))
      scheduler:flush()
      assert.is_true(h.valueOf(offer.exit))
    end)

    it("a count of 0 gives an empty list at once; fractions round down, NaN is 0", function()
      local q = run(Queue.unbounded())
      assert.are.same({ n = 0 }, run(q:takeN(0)))
      assert.are.same({ n = 0 }, run(q:takeBetween(0, 5)))
      assert.are.same({ n = 0 }, run(q:takeN(0 / 0)))
      q:offerAllUnsafe(list(1, 2, 3))
      assert.are.same(list(1, 2), run(q:takeN(2.7)))
    end)
  end)

  it("collect succeeds with every message once the queue finishes", function()
    local q = run(Queue.unbounded())
    local collector = started(q:collect())
    q:offerAllUnsafe(list(1, 2))
    scheduler:flush()
    q:offerUnsafe(3)
    q:finishUnsafe()
    scheduler:flush()
    assert.are.same(list(1, 2, 3), h.valueOf(collector.exit))
  end)

  it("collect fails when the queue fails", function()
    local q = run(Queue.unbounded())
    q:offerUnsafe(1)
    q:failCauseUnsafe(Cause.fail("e"))
    assert.are.same({ "e" }, Cause.failures(h.causeOf(Effect.runSyncExit(q:collect()))))
  end)

  it("into finishes the queue on success, and fails it with the cause on failure", function()
    local a, b = run(Queue.unbounded()), run(Queue.unbounded())
    assert.is_true(run(Queue.into(Effect.void, a)))
    assert.is_true(Cause.isDone(Cause.failures(h.causeOf(a:takeUnsafe()))[1]))
    assert.is_true(run(Queue.into(Effect.fail("e"), b)))
    assert.are.same({ "e" }, Cause.failures(h.causeOf(b:takeUnsafe())))
  end)

  describe("capacity 0", function()
    it("an offer waits until a taker takes its message", function()
      local q = run(Queue.bounded(0))
      local offer = started(q:offer("m"))
      assert.is_nil(offer.exit)
      assert.are.equal("m", run(q:take()))
      scheduler:flush()
      assert.is_true(h.valueOf(offer.exit))
    end)

    it("a waiting taker lets an offer through at once", function()
      local q = run(Queue.bounded(0))
      local taker = started(q:take())
      assert.is_true(run(q:offer("m")))
      scheduler:flush()
      assert.are.equal("m", h.valueOf(taker.exit))
    end)

    it("finish still lets a waiting offer through, then the queue is Done", function()
      local q = run(Queue.bounded(0))
      local offer = started(q:offer("m"))
      run(q:finish())
      assert.are.equal("Closing", q.state)
      assert.are.equal("m", run(q:take()))
      assert.are.equal("Done", q.state)
      scheduler:flush()
      assert.is_true(h.valueOf(offer.exit))
    end)

    it("a sliding queue drops a message when no taker waits", function()
      local q = run(Queue.sliding(0))
      assert.is_true(run(q:offer("lost")))
      local taker = started(q:take())
      assert.is_nil(taker.exit)
      assert.is_true(run(q:offer("m")))
      scheduler:flush()
      assert.are.equal("m", h.valueOf(taker.exit))
    end)
  end)

  it("has every function as a method", function()
    local q = run(Queue.unbounded())
    for _, name in ipairs({
      "offer",
      "offerUnsafe",
      "offerAll",
      "offerAllUnsafe",
      "take",
      "takeAll",
      "takeN",
      "takeBetween",
      "peek",
      "takeUnsafe",
      "clear",
      "finish",
      "finishUnsafe",
      "fail",
      "failCause",
      "failCauseUnsafe",
      "interrupt",
      "shutdown",
      "shutdownUnsafe",
      "await",
      "collect",
      "size",
      "sizeUnsafe",
      "isFull",
      "isFullUnsafe",
    }) do
      assert.are.equal(Queue[name], q[name], name)
    end
    assert.is_true(Queue.isQueue(q))
    assert.is_false(Queue.isQueue({}))
  end)

  it("raises on a non-Queue, a bad capacity or an unknown strategy", function()
    ---@diagnostic disable-next-line: missing-fields
    local ok, err = pcall(Queue.take, {})
    assert.is_false(ok)
    ---@diagnostic disable-next-line: param-type-mismatch
    assert.matches("Queue.take: expected a Queue", err)
    for _, bad in ipairs({ -1, 1.5, 0 / 0, "2" }) do
      assert.has_error(function()
        Queue.bounded(bad)
      end)
      assert.has_error(function()
        Queue.make({ capacity = bad })
      end)
    end
    assert.has_error(function()
      ---@diagnostic disable-next-line: assign-type-mismatch
      Queue.make({ strategy = "random" })
    end)
  end)
end)
