-- Interruption (specifications/07-interruption.md §7) is cooperative. It is
-- delivered only while the fiber is interruptible, recovery handlers never
-- catch it, and finalizers and cancelers always run.

local leffect = require("leffect")
local Cause = leffect.Cause
local Effect = leffect.Effect
local Fiber = leffect.Fiber
local TestScheduler = require("leffect.scheduler.test")
local h = require("spec.helpers")

describe("interruption", function()
  local scheduler
  before_each(function()
    scheduler = TestScheduler.new()
  end)

  local function started(effect)
    return h.started(scheduler, effect)
  end

  describe("of a suspended fiber", function()
    it("cancels its timer", function()
      local fiber = started(Effect.sleep(1000))
      assert.are.equal(1, scheduler:pendingTimers())
      local interrupter = scheduler:fork(fiber:interrupt())
      scheduler:runAll()
      assert.are.equal(0, scheduler:pendingTimers())
      assert.are.equal(0, scheduler:now())
      h.assertInterrupted(fiber:poll())
      assert.are.same({ interrupter.id }, Cause.interruptors(h.causeOf(fiber:poll())))
    end)

    it("runs an effect canceler", function()
      local log, record = h.recorder()
      local fiber = started(Effect.async(function()
        return record("cancelled")
      end))
      fiber:interruptUnsafe()
      scheduler:flush()
      assert.are.same({ "cancelled" }, log)
      h.assertInterrupted(fiber:poll())
    end)

    it("ignores a resume that comes after the interrupt", function()
      local later
      local fiber = started(Effect.async(function(resume)
        later = resume
      end))
      fiber:interruptUnsafe()
      scheduler:flush()
      later(Effect.succeed("too late"))
      scheduler:flush()
      h.assertInterrupted(fiber:poll())
    end)

    it("doesn't run the canceler of an operation that resumed before the wakeup", function()
      local later
      local cancelled = false
      local fiber = started(Effect.async(function(resume)
        later = resume
        return function()
          cancelled = true
        end
      end))
      later(Effect.succeed("done"))
      fiber:interruptUnsafe()
      scheduler:flush()
      assert.is_false(cancelled)
      h.assertInterrupted(fiber:poll())
    end)
  end)

  it("of a fiber that hasn't started runs none of its code", function()
    local ran = false
    local fiber = scheduler:fork(Effect.sync(function()
      ran = true
    end))
    fiber:interruptUnsafe()
    scheduler:flush()
    assert.is_false(ran)
    h.assertInterrupted(fiber:poll())
  end)

  describe("Effect.interrupt", function()
    it("interrupts the current fiber and runs its finalizers", function()
      local log, record = h.recorder()
      local exit, fiber = scheduler:run(Effect.interrupt:ensuring(record("finalizer")))
      assert.are.same({ "finalizer" }, log)
      h.assertInterrupted(exit)
      assert.are.same({ fiber.id }, Cause.interruptors(h.causeOf(exit)))
    end)

    it("is not caught by catchAll, but catchCause can catch it", function()
      local calls = 0
      local exit = scheduler:run(Effect.interrupt:catchAll(function()
        calls = calls + 1
        return Effect.void
      end))
      h.assertInterrupted(exit)
      assert.are.equal(0, calls)

      local caught = scheduler:run(Effect.interrupt:catchCause(function(cause)
        return Effect.succeed(Cause.hasInterruptsOnly(cause))
      end))
      assert.is_true(h.valueOf(caught))
    end)
  end)

  it("skips catchAll and catchCause handlers while interruptible", function()
    local calls = 0
    local function handler()
      calls = calls + 1
      return Effect.succeed("recovered")
    end
    local fiber = started(Effect.never:catchCause(handler):catchAll(handler))
    fiber:interruptUnsafe()
    scheduler:flush()
    assert.are.equal(0, calls)
    h.assertInterrupted(fiber:poll())
  end)

  describe("the skip rule (4.1.5)", function()
    local function failsAfterSleeping()
      return Effect.uninterruptible(Effect.sleep(10):flatMap(function()
        return Effect.fail("x")
      end))
    end

    local function interruptedExit(effect)
      local fiber = started(effect)
      fiber:interruptUnsafe(7)
      scheduler:runAll()
      return fiber:poll()
    end

    local calls
    local function handler()
      calls = calls + 1
      return Effect.succeed("recovered")
    end
    before_each(function()
      calls = 0
    end)

    it("records the interrupt next to a failure from an uninterruptible region", function()
      local cause = h.causeOf(interruptedExit(failsAfterSleeping()))
      assert.are.same({ "Fail", "Interrupt" }, h.tags(cause))
      assert.are.same({ "x" }, (Cause.failures(cause)))
      assert.are.same({ 7 }, Cause.interruptors(cause))
    end)

    it("drops the failures when it skips a recovery handler", function()
      local exit = interruptedExit(failsAfterSleeping():catchAll(handler))
      assert.are.equal(0, calls)
      assert.are.same({ "Interrupt" }, h.tags(h.causeOf(exit)))
    end)

    it("drops a finalizer's failure when it skips a recovery handler", function()
      local exit = interruptedExit(Effect.never:ensuring(Effect.fail("cleanup")):catchAll(handler))
      assert.are.equal(0, calls)
      assert.are.same({ "Interrupt" }, h.tags(h.causeOf(exit)))
    end)

    it("keeps a finalizer's failure when it skips no recovery handler", function()
      local cause = h.causeOf(interruptedExit(Effect.never:ensuring(Effect.fail("cleanup"))))
      assert.are.same({ "Interrupt", "Fail" }, h.tags(cause))
      assert.are.same({ "cleanup" }, (Cause.failures(cause)))
    end)

    it("keeps a finalizer's defect, even when it skips a recovery handler", function()
      local exit = interruptedExit(Effect.never:ensuring(Effect.die("bug")):catchAll(handler))
      assert.are.equal(0, calls)
      local cause = h.causeOf(exit)
      assert.are.same({ "Interrupt", "Die" }, h.tags(cause))
      assert.are.same({ "bug" }, (Cause.defects(cause)))
    end)
  end)

  describe("uninterruptible", function()
    it("defers an interrupt until the region ends, and lets the region complete", function()
      local log, record = h.recorder()
      local effect = Effect.uninterruptible(Effect.sleep(100):flatMap(function()
        return record("region done")
      end)):flatMap(function()
        return record("after the region")
      end)
      local fiber = started(effect)
      fiber:interruptUnsafe()
      scheduler:advance(99)
      assert.is_nil(fiber:poll())
      scheduler:advance(1)
      assert.are.same({ "region done" }, log)
      h.assertInterrupted(fiber:poll())
    end)

    it("works as a method", function()
      local fiber = started(Effect.sleep(10):uninterruptible())
      fiber:interruptUnsafe()
      scheduler:flush()
      assert.is_nil(fiber:poll())
      scheduler:advance(10)
      h.assertInterrupted(fiber:poll())
    end)
  end)

  describe("uninterruptibleMask", function()
    it("makes restore(e) interruptible", function()
      local fiber = started(Effect.uninterruptibleMask(function(restore)
        return restore(Effect.never)
      end))
      fiber:interruptUnsafe()
      scheduler:flush()
      h.assertInterrupted(fiber:poll())
    end)

    it("keeps the code around restore uninterruptible", function()
      local log, record = h.recorder()
      local effect = Effect.uninterruptibleMask(function(restore)
        return Effect.sleep(100)
          :flatMap(function()
            return record("slept")
          end)
          :flatMap(function()
            return restore(record("restored"))
          end)
      end)
      local fiber = started(effect)
      fiber:interruptUnsafe()
      scheduler:advance(99)
      assert.is_nil(fiber:poll())
      scheduler:advance(1)
      assert.are.same({ "slept" }, log)
      h.assertInterrupted(fiber:poll())
    end)

    it("nests: an inner restore keeps the outer region uninterruptible", function()
      local fiber = started(Effect.uninterruptibleMask(function()
        return Effect.uninterruptibleMask(function(restore)
          return restore(Effect.sleep(100))
        end)
      end))
      fiber:interruptUnsafe()
      scheduler:advance(99)
      assert.is_nil(fiber:poll())
      scheduler:advance(1)
      h.assertInterrupted(fiber:poll())
    end)
  end)

  it("interruptible(e) fails at once when the fiber was already interrupted", function()
    local ran = false
    local effect = Effect.uninterruptible(Effect.sleep(10):flatMap(function()
      return Effect.interruptible(Effect.sync(function()
        ran = true
      end))
    end))
    local fiber = started(effect)
    fiber:interruptUnsafe()
    scheduler:advance(10)
    assert.is_false(ran)
    h.assertInterrupted(fiber:poll())
  end)

  describe("requested while the fiber runs", function()
    it("is delivered when the request comes in the fiber's last step", function()
      local exit = scheduler:run(Effect.withFiber(function(fiber)
        return Effect.sync(function()
          fiber:interruptUnsafe(fiber.id)
        end)
      end))
      h.assertInterrupted(exit)
    end)

    it("is delivered when the request comes from register", function()
      local cancelled = false
      local exit = scheduler:run(Effect.withFiber(function(fiber)
        return Effect.async(function()
          fiber:interruptUnsafe(fiber.id)
          return function()
            cancelled = true
          end
        end)
      end))
      h.assertInterrupted(exit)
      assert.is_true(cancelled)
    end)
  end)

  describe("fiber:interrupt", function()
    local function cleansUpSlowly(record)
      return Effect.never:ensuring(Effect.sleep(100):flatMap(function()
        return record("target cleaned up")
      end))
    end

    it("returns only after the target's finalizers finish", function()
      local log, record = h.recorder()
      local target = started(cleansUpSlowly(record))
      scheduler:fork(target:interrupt():flatMap(function()
        return record("interrupt returned")
      end))
      scheduler:runAll()
      assert.are.same({ "target cleaned up", "interrupt returned" }, log)
      assert.are.equal(100, scheduler:now())
    end)

    it("interruptFork returns at once", function()
      local log, record = h.recorder()
      local target = started(cleansUpSlowly(record))
      scheduler:fork(target:interruptFork():flatMap(function()
        return record("interruptFork returned")
      end))
      scheduler:flush()
      assert.are.same({ "interruptFork returned" }, log)
      scheduler:runAll()
      assert.are.same({ "interruptFork returned", "target cleaned up" }, log)
    end)

    it("does nothing to a fiber that is already done", function()
      local target = started(Effect.succeed("finished"))
      h.valueOf(scheduler:run(target:interrupt()))
      assert.are.equal("finished", h.valueOf(target:poll()))
    end)

    it("records every interruptor", function()
      local target = started(Effect.never)
      local a = scheduler:fork(target:interruptFork())
      local b = scheduler:fork(target:interruptFork())
      scheduler:runAll()
      assert.are.same({ a.id, b.id }, Cause.interruptors(h.causeOf(target:poll())))
    end)

    it("removes the observer an interrupted awaiter left on its target", function()
      local target = started(Effect.never)
      local waiter = started(target:await())
      assert.are.equal(1, #target.observers)
      waiter:interruptUnsafe()
      scheduler:flush()
      h.assertInterrupted(waiter:poll())
      assert.are.equal(0, #target.observers)
    end)
  end)

  it("Fiber.interruptAll interrupts every fiber and waits for all of them", function()
    local log, record = h.recorder()
    local a = started(Effect.never:ensuring(record("a cleaned up")))
    local b = started(Effect.never:ensuring(record("b cleaned up")))
    local exit = scheduler:run(Fiber.interruptAll({ a, b }):flatMap(function()
      return record("all done")
    end))
    h.valueOf(exit)
    assert.are.same({ "a cleaned up", "b cleaned up", "all done" }, log)
  end)
end)
